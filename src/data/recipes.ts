export function getRecipeBySlug(slug: string) {
  return recipes.find((r) => r.slug === slug);
}

export function getRelatedRecipes(recipe: Recipe, limit = 3) {
  return recipes
    .filter((r) => r.id !== recipe.id && (r.state === recipe.state || r.cuisine === recipe.cuisine))
    .slice(0, limit);
}

export function getTopRecipes(limit = 5) {
  return [...recipes].sort((a, b) => b.rating - a.rating).slice(0, limit);
}
